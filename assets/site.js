function initGate(){
  const modal = $('#gateModal');
  const openers = $$('.resource-open');
  const close = ()=> modal.classList.remove('open');
  openers.forEach(btn=> btn.addEventListener('click', ()=>{
    state.gateAsset = btn.dataset.asset;
    state.gateAssetLabel = btn.dataset.label;
    $('#gateAssetName').textContent = btn.dataset.label;
    modal.classList.add('open');
    $('#gateName').focus();
  }));
  $('#gateClose')?.addEventListener('click', close);
  $('#gateCancel')?.addEventListener('click', close);
  modal?.addEventListener('click', (e)=>{ if(e.target === modal) close(); });
  $('#gateForm')?.addEventListener('submit', (e)=>{
    e.preventDefault();
    const fd = new FormData(e.target);
    if(!fd.get('agree')) return;
    const params = new URLSearchParams({
      subject:`VitaCoreX Resource Unlock — ${state.gateAssetLabel}`,
      body:`Name: ${fd.get('name')}\nCompany: ${fd.get('company')}\nPhone: ${fd.get('phone')}\nEmail: ${fd.get('email')}\nResource: ${state.gateAssetLabel}`
    });
    window.open(`mailto:VitaCoreXllc@gmail.com?${params.toString()}`,'_blank');
    close();
    if(state.gateAsset){
      const a = document.createElement('a');
      a.href = state.gateAsset;
      a.target='_blank';
      a.rel='noopener';
      a.click();
    }
  });
}

function initCareers(){
  const form = $('#careersForm');
  const applyBtn = $('#applyEmail');
  const update = ()=>{
    const requiredOk = $('#careerName').value.trim() && $('#careerEmail').value.trim() && $('#careerRole').value.trim() && $('#careerBg').value.trim();
    applyBtn.setAttribute('aria-disabled', requiredOk ? 'false' : 'true');
  };
  ['input','change','keyup'].forEach(ev => form?.addEventListener(ev, update));
  update();
  applyBtn?.addEventListener('click', (e)=>{
    if(applyBtn.getAttribute('aria-disabled') === 'true'){ e.preventDefault(); return; }
    const name = $('#careerName').value.trim();
    const email = $('#careerEmail').value.trim();
    const role = $('#careerRole').value.trim();
    const bg = $('#careerBg').value.trim();
    const params = new URLSearchParams({
      subject:`VitaCoreX Careers Application — ${role}`,
      body:`Full Name: ${name}\nEmail: ${email}\nRole of Interest: ${role}\nBackground:\n${bg}`
    });
    applyBtn.href = `mailto:VitaCoreXllc@gmail.com?${params.toString()}`;
  });
}

