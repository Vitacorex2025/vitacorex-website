function applyTranslations(lang){
  state.lang = lang;
  localStorage.setItem('vcx_lang', lang);
  document.documentElement.lang = lang;
  const dict = I18N[lang] || I18N.en;
  $$('[data-i18n]').forEach(el=>{
    const key = el.dataset.i18n;
    if(dict[key] !== undefined) el.textContent = dict[key];
  });
  $$('[data-i18n-placeholder]').forEach(el=>{
    const key = el.dataset.i18nPlaceholder;
    if(dict[key] !== undefined) el.placeholder = dict[key];
  });
  $$('.langbtn').forEach(btn => btn.classList.toggle('active', btn.dataset.lang===lang));
  updateClocks();
}

function initLang(){
  if(!['en','ru','es'].includes(state.lang)) state.lang='en';
  applyTranslations(state.lang);
  $$('.langbtn').forEach(btn => btn.addEventListener('click', ()=> applyTranslations(btn.dataset.lang)));
}

function formatTime(zone){
  const now = new Date();
  return new Intl.DateTimeFormat(undefined,{
    hour:'2-digit', minute:'2-digit', timeZone: zone
  }).format(now);
}
function updateClocks(){
  $('#vcxTime').textContent = formatTime('America/New_York') + ' Tampa';
  $('#userTime').textContent = formatTime(Intl.DateTimeFormat().resolvedOptions().timeZone);
}
function initClocks(){
  updateClocks();
  setInterval(updateClocks, 1000);
}

